package org.aiupcycler.worker.pairing

import java.io.ByteArrayInputStream
import java.io.File
import java.security.KeyFactory
import java.security.MessageDigest
import java.security.Signature
import java.security.cert.CertificateFactory
import java.security.cert.X509Certificate
import java.security.spec.PKCS8EncodedKeySpec
import java.util.Base64
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The committed pairing fixtures, issued by the Rust `NodeCa` the enrollment
 * endpoint itself uses (spec D-B3; `core/examples/pairing_fixtures.rs`).
 *
 * These fixtures are not byte-regenerable, so this suite is the guard instead
 * of a sync check: it pins the properties the Android worker depends on -
 * chain trust, single-role EKUs, SANs, long validity, and the fingerprint
 * algorithm - and fails loudly if the Rust side ever starts issuing shapes
 * this app cannot use.
 *
 * Every material here is throwaway test data generated by the example; it
 * never guards anything real.
 */
class PairingFixtureTest {

    private val ca: X509Certificate by lazy { certificate("ca.pem") }
    private val server: X509Certificate by lazy { certificate("server-cert.pem") }
    private val client: X509Certificate by lazy { certificate("client-cert.pem") }
    private val rogueCa: X509Certificate by lazy { certificate("rogue-ca.pem") }
    private val rogue: X509Certificate by lazy { certificate("rogue-cert.pem") }

    @Test
    fun theCaSignsTheWorkersServerCertificate() {
        server.verify(ca.publicKey)
    }

    @Test
    fun theCaSignsTheWorkersClientCertificate() {
        client.verify(ca.publicKey)
    }

    @Test
    fun anUnrelatedCaDoesNotSignTheFixtureChain() {
        // The negative path the mTLS server test relies on: a certificate from
        // another CA must not verify against this one.
        val failed = runCatching { rogue.verify(ca.publicKey) }.isFailure
        assertTrue("a foreign certificate must not verify against the fixture CA", failed)
        rogue.verify(rogueCa.publicKey)
    }

    @Test
    fun theCaIsACertificateAuthority() {
        // `getBasicConstraints` is `Integer.MAX_VALUE` for a CA with no path
        // length, and `-1` for a certificate with no basicConstraints
        // extension - which is exactly what the two leaf identities carry:
        // they must never be usable to sign anything.
        assertEquals("CA basic constraint", Int.MAX_VALUE, ca.basicConstraints)
        assertEquals(-1, server.basicConstraints)
        assertEquals(-1, client.basicConstraints)
    }

    @Test
    fun eachIdentityCarriesExactlyItsOwnRole() {
        // The certificates are single-purpose by contract (docs/api.md #3.4);
        // a dual-purpose certificate would make the role checks meaningless.
        assertEquals(listOf("1.3.6.1.5.5.7.3.1"), server.extendedKeyUsage)
        assertEquals(listOf("1.3.6.1.5.5.7.3.2"), client.extendedKeyUsage)
    }

    @Test
    fun theServerCertificateCoversTheLoopbackDialAddresses() {
        // `load_secure` validates the server certificate against the address it
        // dialed; the fixture server is dialed at loopback by the JVM tests.
        val names = server.subjectAlternativeNames!!.map { it[1].toString() }
        assertTrue("127.0.0.1 must be a SAN, got $names", names.contains("127.0.0.1"))
        assertTrue("localhost must be a SAN, got $names", names.contains("localhost"))
    }

    @Test
    fun theClientCertificateDeclaresNoSubjectAlternativeName() {
        // A client identity is not dialable, so it must not assert an address.
        val names = client.subjectAlternativeNames
        assertTrue(names == null || names.isEmpty())
    }

    @Test
    fun everyCertificateOutlivesAnyRealisticBuild() {
        // rcgen's default validity runs to 4096-01-01; these PEMs are committed
        // and loaded by tests, so an expiry would turn CI red on a calendar
        // date rather than on a code change.
        val floor = java.time.Instant.parse("2100-01-01T00:00:00Z")
        for ((name, certificate) in listOf(
            "ca" to ca,
            "server" to server,
            "client" to client,
            "rogue-ca" to rogueCa,
            "rogue" to rogue,
        )) {
            assertTrue(
                "$name expires ${certificate.notAfter}, too soon for a committed fixture",
                certificate.notAfter.toInstant().isAfter(floor),
            )
        }
    }

    @Test
    fun theGoldenFingerprintIsTheCaDerDigest() {
        // The QR carries this digest; `NodeCa::fingerprint` computes it as
        // lowercase hex SHA-256 over the CA's DER. If this ever disagrees, a
        // scanned code would never match a real master.
        val golden = Regex("\"fingerprint\"\\s*:\\s*\"([0-9a-f]{64})\"")
            .find(File(FIXTURE_DIR, "enroll_response.json").readText())!!
            .groupValues[1]

        val digest = MessageDigest.getInstance("SHA-256").digest(ca.encoded)
        assertEquals(golden, digest.joinToString("") { "%02x".format(it) })
    }

    @Test
    fun theGoldenResponseCarriesTheSameCertificatesAsThePemFiles() {
        val golden = File(FIXTURE_DIR, "enroll_response.json").readText()
        for (name in listOf("ca", "server-cert", "server-key", "client-cert", "client-key")) {
            val pem = File(FIXTURE_DIR, "$name.pem").readText()
            val body = pem.substringAfter('\n').substringBefore("-----END")
                .replace("\r", "").replace("\n", "")
            // The JSON side escapes rcgen's CRLF line endings, so the embedded
            // form is the PEM body with those escapes removed.
            assertTrue(
                "enroll_response.json must embed $name exactly as the PEM file does",
                golden.replace("\\r\\n", "").replace("\\n", "").contains(body),
            )
        }
    }

    @Test
    fun thePrivateKeysArePkcs8AndParse() {
        // rcgen 0.14 serializes keys as PKCS#8; the mTLS server (S4) feeds these
        // straight into an SSLContext, so a format change must fail here first.
        for (name in listOf("server-key", "client-key", "rogue-key")) {
            val pem = File(FIXTURE_DIR, "$name.pem").readText()
            assertTrue("$name must be a PKCS#8 PRIVATE KEY block", pem.contains("BEGIN PRIVATE KEY"))
            val der = Base64.getMimeDecoder().decode(
                pem.substringAfter('\n').substringBefore("-----END"),
            )
            assertNotNull(KeyFactory.getInstance("EC").generatePrivate(PKCS8EncodedKeySpec(der)))
        }
    }

    @Test
    fun theServerKeyMatchesTheServerCertificate() {
        // Serving requires the pair to belong together; a mismatch is exactly
        // the failure a fresh fixture run could introduce unnoticed.
        val certificate = server
        val key = KeyFactory.getInstance("EC").generatePrivate(
            PKCS8EncodedKeySpec(
                Base64.getMimeDecoder().decode(
                    File(FIXTURE_DIR, "server-key.pem").readText()
                        .substringAfter('\n').substringBefore("-----END"),
                ),
            ),
        )

        val signature = Signature.getInstance("SHA256withECDSA")
        signature.initSign(key)
        signature.update("pairing fixture probe".toByteArray())
        val signed = signature.sign()

        val verifier = Signature.getInstance("SHA256withECDSA")
        verifier.initVerify(certificate.publicKey)
        verifier.update("pairing fixture probe".toByteArray())
        assertTrue("server-key.pem must match server-cert.pem", verifier.verify(signed))
    }

    private fun certificate(name: String): X509Certificate {
        val factory = CertificateFactory.getInstance("X.509")
        return File(FIXTURE_DIR, name).inputStream().use {
            factory.generateCertificate(ByteArrayInputStream(it.readBytes())) as X509Certificate
        }
    }

    private companion object {
        val FIXTURE_DIR = File("src/test/resources/pairing")
    }
}
